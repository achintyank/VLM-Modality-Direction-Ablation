#@title Helper functions
def fetch_image(url, timeout=10):
    """Download image from URL -> PIL RGB. Return None if dead/broken/tiny."""
    try:
        resp = requests.get(url, timeout=timeout, headers={"User-Agent": "Mozilla/5.0"})
        resp.raise_for_status()
        img = Image.open(io.BytesIO(resp.content)).convert("RGB")
        if min(img.size) < 64:
            return None
        img.thumbnail((1536, 1536))
        return img
    except Exception:
        return None


def build_messages(image, caption):
    return [{"role": "user", "content": [
        {"type": "image", "image": image},
        {"type": "text", "text": caption},
        {"type": "text", "text": "\nWhat is this image?"},
    ]}]


def build_text_messages(caption):
    """Same prompt without the image: the caption is then conditioned only on the chat prefix (the question comes after it)."""
    return [{"role": "user", "content": [
        {"type": "text", "text": caption},
        {"type": "text", "text": "\nWhat is this image?"},
    ]}]


def caption_token_indices(text, caption, offsets):
    """Indices of tokens whose char span lies inside the caption's span in `text` (None if not found)."""
    char_start = text.find(caption)
    if char_start == -1:
        return None
    char_end = char_start + len(caption)
    idxs = [i for i, (s, e) in enumerate(offsets) if e > s and s >= char_start and e <= char_end]
    return idxs or None


def prepare_inputs(image, caption):
    """Tokenize the image prompt. Returns (inputs, vision_mask, caption_mask) on CPU, or None if the example can't be aligned."""
    text = processor.apply_chat_template(build_messages(image, caption), tokenize=False, add_generation_prompt=True)
    inputs = processor(text=[text], images=[image], return_tensors="pt")
    input_ids = inputs["input_ids"][0]

    vision_mask = input_ids == image_token_id
    n_img = int(vision_mask.sum())
    if n_img == 0:
        return None
    img_start = vision_mask.nonzero(as_tuple=True)[0][0].item()
    shift = n_img - 1

    raw_enc = processor.tokenizer(text, return_offsets_mapping=True, add_special_tokens=False)
    if len(raw_enc["input_ids"]) + shift != len(input_ids):
        return None
    raw_idxs = caption_token_indices(text, caption, raw_enc["offset_mapping"])
    if raw_idxs is None:
        return None
    cap_idxs = [i + shift if i > img_start else i for i in raw_idxs]
    caption_mask = torch.zeros_like(vision_mask)
    caption_mask[cap_idxs] = True
    if (caption_mask & vision_mask).any():
        return None
    return inputs, vision_mask, caption_mask


def prepare_text_inputs(caption):
    """Tokenize the caption-only prompt (no image). Returns (inputs, caption_mask) on CPU, or None."""
    text = processor.apply_chat_template(build_text_messages(caption), tokenize=False, add_generation_prompt=True)
    enc = processor.tokenizer(text, return_offsets_mapping=True, add_special_tokens=False)
    idxs = caption_token_indices(text, caption, enc["offset_mapping"])
    if idxs is None:
        return None
    input_ids = torch.tensor(enc["input_ids"])
    caption_mask = torch.zeros(len(input_ids), dtype=torch.bool)
    caption_mask[idxs] = True
    return {"input_ids": input_ids[None], "attention_mask": torch.ones(1, len(input_ids), dtype=torch.long)}, caption_mask


