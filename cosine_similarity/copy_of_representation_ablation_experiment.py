def matched_and_mismatched(img, txt):
    """Per layer: cos(img_i, txt_i) and mean_{j≠i} cos(img_i, txt_j)."""
    matched, mism = torch.zeros(N_LAYERS + 1, n), torch.zeros(N_LAYERS + 1, n)
    for L in range(N_LAYERS + 1):
        S = F.normalize(img[L].to(device), dim=-1) @ F.normalize(txt[L].to(device), dim=-1).T   # [n, n]
        d = S.diagonal()
        matched[L], mism[L] = d.cpu(), ((S.sum(1) - d) / (n - 1)).cpu()
    return matched, mism

def metrics(res):
    img = res["img"]
    m_cond = torch.cat([img, anchor], dim=1).mean(1, keepdim=True)
    raw, raw_mism = matched_and_mismatched(img, anchor)
    cen, cen_mism = matched_and_mismatched(img - m_cond, anchor - m_cond)
    stale, _ = matched_and_mismatched(img - m_base, anchor - m_base)
    modal, _ = matched_and_mismatched(img - img.mean(1, keepdim=True), anchor - anchor.mean(1, keepdim=True))
    return {
        "raw": raw,                                                                 # cos(mu_image, caption-only anchor)
        "centered": cen,                                                            # pooled per-condition mean subtracted
        "centered_stale": stale,                                                    # baseline mean subtracted from every condition (artifact)
        "centered_modality": modal,                                                 # each modality centered on its own mean (gap removed by construction)
        "contrast": raw - raw_mism,                                                 # matched − mean mismatched: content-specific alignment
        "centered_contrast": cen - cen_mism,
        "raw_ctx_anchor": F.cosine_similarity(img, anchor_ctx, dim=-1),            # fixed in-context anchor (baseline caption reps)
        "moving_anchor": F.cosine_similarity(img, res["txt"], dim=-1),             # same-pass caption reps: the earlier, confounded metric
        "txt_drift": F.cosine_similarity(res["txt"], baseline["txt"], dim=-1),     # how far the in-context caption reps moved
    }

