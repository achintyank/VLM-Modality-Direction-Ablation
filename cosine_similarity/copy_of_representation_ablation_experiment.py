#@title Ablation hook on the vision embedding layer
def make_projection_ablation_hook(v: torch.Tensor):
    """Forward hook: output <- output − (output · v_hat) v_hat   (fp32 math, cast back to the module dtype)."""
    v_hat = v.flatten().float()
    v_hat = (v_hat / v_hat.norm()).to(device)

    def hook_fn(module, args, output):
        h = output.float()
        return (h - (h @ v_hat).unsqueeze(-1) * v_hat).to(output.dtype)
    return hook_fn


def vision_modules(include_deepstack=True):
    """Every tensor the vision encoder hands to the LM, with the hidden_states index where it first appears.

    Qwen2-VL: the merger output IS hidden_states[0] at image positions (masked_scatter'd into inputs_embeds),
              and it is the ENTIRE vision->LM interface — there are no deepstack mergers.
    Qwen3-VL: additionally three deepstack mergers carry mid-level ViT features that are ADDED at image
              positions after decoder layers 0,1,2 -> they first appear in hidden_states[1],[2],[3].

    All of these live inside model.model.visual: no language-model module is hooked, so the intervention
    stays confined to the vision encoder's output no matter which model is loaded."""
    mods = [("merger", model.model.visual.merger, 0)]
    if include_deepstack and HAS_DEEPSTACK:
        mods += [(f"deepstack[{k}]", m, k + 1)
                 for k, m in enumerate(model.model.visual.deepstack_merger_list)]
    return mods


def vision_ablation_hooks(v, include_deepstack=True):
    hook = make_projection_ablation_hook(v)
    return [(m, hook) for _, m, _ in vision_modules(include_deepstack)]


def capture_hooks(store, include_deepstack=True):
    """Record each vision module's output as the LM receives it (deepstack features are additive at image
    positions, so their individual projections can't be read off the residual stream — grab them here)."""
    def make(name):
        def fn(module, args, output):
            store[name] = output.detach().float()
        return fn
    return [(m, make(name)) for name, m, _ in vision_modules(include_deepstack)]


