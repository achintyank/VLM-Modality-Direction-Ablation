#@title Forward passes
def run_pass(cached, hooks=(), desc="pass", indices=None):
    """Forward the examples `indices` (default: all) with `hooks` = [(module, hook_fn), ...] registered.
    Returns, per index L in 0..N_LAYERS and example (float32, CPU):
      img[L, j] = mu_image(L)    mean image-token activation at hidden_states[L]
      txt[L, j] = in-context caption mean of the same forward pass (moves when the image is ablated)
    """
    indices = list(range(len(cached))) if indices is None else list(indices)
    img = torch.zeros(N_LAYERS + 1, len(indices), HIDDEN)
    txt = torch.zeros(N_LAYERS + 1, len(indices), HIDDEN)
    handles = [m.register_forward_hook(h) for m, h in hooks]
    try:
        for j, i in enumerate(tqdm(indices, desc=desc)):
            inputs, vmask, cmask = cached[i]
            inputs = {k: v.to(device) for k, v in inputs.items()}
            vm, cm = vmask.to(device), cmask.to(device)
            with torch.no_grad():
                out = model(**inputs, output_hidden_states=True)
                for L in range(N_LAYERS + 1):
                    acts = out.hidden_states[L][0].float()
                    img[L, j] = acts[vm].mean(0).cpu()
                    txt[L, j] = acts[cm].mean(0).cpu()
            del out
    finally:
        for h in handles:
            h.remove()
    return {"img": img, "txt": txt}


def run_text_pass(cached_text, desc="caption-only anchor"):
    """Caption-only forward passes (no image): the fixed text anchor mu_caption0(L), never conditioned on an image."""
    txt = torch.zeros(N_LAYERS + 1, len(cached_text), HIDDEN)
    for i, (inputs, cmask) in enumerate(tqdm(cached_text, desc=desc)):
        inputs = {k: v.to(device) for k, v in inputs.items()}
        cm = cmask.to(device)
        with torch.no_grad():
            out = model(**inputs, output_hidden_states=True)
            for L in range(N_LAYERS + 1):
                txt[L, i] = out.hidden_states[L][0][cm].float().mean(0).cpu()
        del out
    return txt


