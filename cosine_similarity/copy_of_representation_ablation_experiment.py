def run_crossfit(desc=""):
    """Ablate the v0 estimated on fold k on the examples of fold 1-k; stitch into full [N_LAYERS+1, n, H] arrays."""
    out = {"img": torch.zeros(N_LAYERS + 1, n, HIDDEN), "txt": torch.zeros(N_LAYERS + 1, n, HIDDEN)}
    for k in (0, 1):
        idx = folds[1 - k]
        r = run_pass(cached, hooks=vision_ablation_hooks(fold_vectors[k]),
                     desc=f"{desc}: v0 from fold {k} -> examples of fold {1-k}", indices=idx.tolist())
        out["img"][:, idx] = r["img"]
        out["txt"][:, idx] = r["txt"]
    return out

